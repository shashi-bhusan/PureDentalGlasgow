                            <h5>Dentures </h5>
                            <!--<div class="pm-column-title-divider">
                                <img src="../img/divider-icon.png" width="29" height="29" alt="icon">
                            </div>-->
                            <p>ade of acrylic (plastic) or metal, dentures are removable replacement teeth secured to a plate and often held in place by implants or adjacent teeth. With careful planning, construction and fitting, modern dentures are natural looking and fit accurately.</p>

<p>There are several types of Dentures available:</p>

<ul>
	<li>Full or complete dentures - replacing all upper or lower teeth</li>
	<li>Partial dentures - replacing one tooth or a few missing teeth</li>
	<li>Metal or cobalt chrome dentures - replacing all or a few missing teeth but taking support from teeth and gums.</li>
</ul>

<p>Our qualified dental professionals will advise you on dental care and, where suitable, provide you with options for alternatives to dentures such as&nbsp;<a href="http://puredentalglasgow.com/dental-implants.php">DENTAL IMPLANTS</a>&nbsp;and&nbsp;<a href="http://puredentalglasgow.com/bridges.php">BRIDGES</a>.</p>

