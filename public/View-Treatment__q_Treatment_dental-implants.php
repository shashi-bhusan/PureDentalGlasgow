                    <div class="row">
                        <div class="col-lg-12 pm-columnPadding30 pm-center" >
                            <h5>Bridges </h5>
                            <!--<div class="pm-column-title-divider">
                                <img src="../img/divider-icon.png" width="29" height="29" alt="icon">
                            </div>-->
                            <p>If you are missing a tooth, a simple solution can be to have a bridge fitted. The bridge is cemented onto your existing teeth. Modern bridges are made using porcelain or ceramic and are carefully matched to the natural colour of your teeth.</p>

<p>There are many advantages to the dental bridge:</p>

<ul>
	<li>you can smile again</li>
	<li>you can speak and chew properly again</li>
	<li>the shape of your face is maintained</li>
	<li>it takes away the strain from the teeth at either side - the gap left by a missing tooth can mean your &lsquo;bite&rsquo; is affected as the teeth either side of the gap lean into the gap and change the way the upper and lower teeth bite together</li>
</ul>

<p>Come and speak to one of our dentists who will advise you on the best options for you.</p>
