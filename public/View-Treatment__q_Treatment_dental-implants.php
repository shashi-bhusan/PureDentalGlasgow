                        <div class="col-lg-12 pm-columnPadding30 pm-center" >
                            <h5>Dental Implants </h5>
                            <!--<div class="pm-column-title-divider">
                                <img src="../img/divider-icon.png" width="29" height="29" alt="icon">
                            </div>-->
                            <p>Missing tooth or teeth apart from looking unsightly may cause harm to the adjacent teeth. Neighboring teeth can grow into spaces disrupting the bite and causing food packing in interdental spaces.</p>

<p>Dental implant, or tooth implant, is a long fixed term solution to replace a missing tooth. A titanium screw is gently threaded in the region of the missing tooth, replacing tooth root. Once the dental implant has had time to integrate with your bone, usually a few months, we attach a crown to this. They feel and look like a natural tooth and unlike a bridge we don&rsquo;t have to prepare the adjacent teeth to support them.</p>

<p>Because several factors affect the treatment planning, we recommend you see our dental implant surgeon for an implant assessment and see if dental implants are the solution for you.</p>

